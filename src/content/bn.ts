const ordinals = ["", "প্রথম", "দ্বিতীয়", "তৃতীয়", "চতুর্থ", "পঞ্চম", "ষষ্ঠ", "সপ্তম", "অষ্টম", "নবম", "দশম", "একাদশ", "দ্বাদশ"];

/** Translates a known term; "Class 8" → "অষ্টম শ্রেণি"; unknown text is returned unchanged. */
export function term(s: string): string {
  if (!s) return s;
  if (terms[s]) return terms[s];
  if (qualifications[s]) return qualifications[s];
  const cls = s.match(/^Class (\d{1,2})$/);
  if (cls) return `${ordinals[Number(cls[1])]} শ্রেণি`;
  const range = s.match(/^Class (\d{1,2}) – (\d{1,2})$/);
  if (range) return `${ordinals[Number(range[1])]} – ${ordinals[Number(range[2])]} শ্রেণি`;
  return s;
}

