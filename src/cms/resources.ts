export function getResource(key: string): ResourceConfig | undefined {
  return resources.find((r) => r.key === key);
}

/** Fields including the automatic publishing fields */
export function resourceFields(r: ResourceConfig): Field[] {
  if (!r.publishable) return r.fields;
  return [
    ...r.fields,
    { name: "status", label: "Status", type: "select", options: statusOptions, required: true, span: 1 },
    { name: "publishAt", label: "Publish at (for scheduled)", type: "datetime", span: 1, help: "Scheduled items go live at this time" },
  ];
}
