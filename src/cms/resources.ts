import type { Field, Option } from "./fields";
import type { Area } from "./permissions";

/**
 * Collection resources managed by the CMS. Each entry becomes a MongoDB
 * collection (one Mongoose model per resource), an admin list/edit screen and
 * server-validated CRUD actions. `tags` are the public cache tags refreshed
 * whenever the resource changes.
 */

export type Column = {
  key: string;
  label: string;
  format?: "text" | "date" | "datetime" | "badge" | "boolean" | "image" | "bn" | "count";
};

export type ResourceConfig = {
  key: string;
  label: string;
  singular: string;
  description?: string;
  area: Area;
  fields: Field[];
  columns: Column[];
  titleField: string;
  searchFields: string[];
  filters?: { key: string; label: string; options?: Option[]; taxonomy?: string }[];
  sort: { field: string; dir: 1 | -1 };
  /** Adds status (draft / published / scheduled) and publishAt fields */
  publishable?: boolean;
  /** Field used to generate the slug when it is left empty */
  slugSource?: string;
  unique?: string[];
  indexes?: Record<string, 1 | -1>[];
  tags: string[];
  canCreate?: boolean;
  /** Enables CSV export on the list page */
  exportable?: boolean;
};

